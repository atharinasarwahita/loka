    private void loadDashboardAdmin() {
        int totalPesanan = 0;
        double totalOmzetLoka = 0.0;
        List<Pesanan> listPesanan = control.ambilSemuaPesanan();
        if (listPesanan != null) {
            totalPesanan = listPesanan.size();
            for (Pesanan p : listPesanan) {
                String status = String.valueOf(p.getStatusPesanan()).toUpperCase();
                if (status.contains("SELESAI") || status.contains("SUCCESS")) {
                    totalOmzetLoka += p.getTotalBayar();
                }
            }
        }

        int totalUmkm = 0;
        List<Penjual> listPenjual = control.ambilSemuaPenjual();
        if (listPenjual != null) {
            totalUmkm = listPenjual.size();
        }

        int totalPembeli = 0;
        List<model.Pembeli> listPembeli = control.ambilSemuaPembeli();
        if (listPembeli != null) {
            totalPembeli = listPembeli.size();
        }

        NumberFormat formatRupiah = NumberFormat.getCurrencyInstance(new Locale("id", "ID"));

        jLblTotalPendapatan.setText(formatRupiah.format(totalOmzetLoka)); 

        jLblTotalUmkm.setText(totalUmkm + " UMKM (" + totalPesanan + " Pesanan)"); 

        jLblTotalPembeli.setText(String.valueOf(totalPembeli));
    }


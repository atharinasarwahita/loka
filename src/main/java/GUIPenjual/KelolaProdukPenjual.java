    private void jBtnUpdateStokActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBtnUpdateStokActionPerformed
    int selectedRow = jTblDaftarProduk.getSelectedRow();
        if (selectedRow == -1) {
            JOptionPane.showMessageDialog(this, "Pilih produk dari tabel yang ingin diubah stoknya!", "Peringatan", JOptionPane.WARNING_MESSAGE);
            return;
        }

        int idProduk = Integer.parseInt(jTblDaftarProduk.getValueAt(selectedRow, 0).toString());

        String stokBaruStr = JOptionPane.showInputDialog(this, "Masukkan Stok Baru:", "Update Stok Produk", JOptionPane.QUESTION_MESSAGE);

        if (stokBaruStr != null && !stokBaruStr.trim().isEmpty()) {
            try {
                int stokBaru = Integer.parseInt(stokBaruStr.trim());

                for (Produk p : control.ambilSemuaProduk()) {
                    if (p.getIdProduk() == idProduk) {

                        enums.StatusProduk statusBaru;
                        if (stokBaru <= 0) {
                            statusBaru = enums.StatusProduk.Habis;
                        } else if (stokBaru <= 5) {
                            statusBaru = enums.StatusProduk.Kritis;
                        } else if (stokBaru <= 15) {
                            statusBaru = enums.StatusProduk.Waspada;
                        } else {
                            statusBaru = enums.StatusProduk.Aman;
                        }

                        control.ubahProduk(
                            p.getIdProduk(), 
                            p.getPenjualIdPengguna(), 
                            p.getNamaProduk(),
                            p.getDeskripsi(), 
                            p.getKategori(), 
                            p.getGambarProduk(),
                            p.getHarga(), 
                            p.getBeratGram(), 
                            stokBaru, 
                            statusBaru,
                            p.getIzinJual(), 
                            p.getJumlahShare()
                        );
                        break;
                    }
                }
                JOptionPane.showMessageDialog(this, "Stok produk berhasil diperbarui!", "Sukses", JOptionPane.INFORMATION_MESSAGE);
                loadDataTabel();

            } catch (NumberFormatException e) {
                JOptionPane.showMessageDialog(this, "Input stok harus berupa angka!", "Error", JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_jBtnUpdateStokActionPerformed

    private void jBtnHapusProdukActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBtnHapusProdukActionPerformed
        int selectedRow = jTblDaftarProduk.getSelectedRow();
        if (selectedRow == -1) {
            JOptionPane.showMessageDialog(this, "Pilih produk dari tabel yang ingin dihapus!", "Peringatan", JOptionPane.WARNING_MESSAGE);
            return;
        }

        int idProduk = (int) jTblDaftarProduk.getValueAt(selectedRow, 0);
        int konfirmasi = JOptionPane.showConfirmDialog(this, "Yakin ingin menghapus produk ini?", "Konfirmasi Hapus", JOptionPane.YES_NO_OPTION);

        if (konfirmasi == JOptionPane.YES_OPTION) {
            control.hapusProduk(idProduk);
            JOptionPane.showMessageDialog(this, "Produk berhasil dihapus!", "Sukses", JOptionPane.INFORMATION_MESSAGE);
            loadDataTabel();
        }
    }//GEN-LAST:event_jBtnHapusProdukActionPerformed


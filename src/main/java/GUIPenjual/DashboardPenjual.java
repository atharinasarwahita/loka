    private void loadDashboardData() {
        // 1. Set Nama Toko di Header Banner (jLabel3)
        List<Penjual> listPenjual = control.ambilSemuaPenjual();
        if (listPenjual != null) {
            for (Penjual p : listPenjual) {
                if (p.getIdPengguna() == this.idPengguna) {
                    jLabel3.setText(p.getNamaToko());
                    break;
                }
            }
        }

        int jumlahProduk = 0;
        List<Produk> listProduk = control.ambilSemuaProduk();
        if (listProduk != null) {
            for (Produk prod : listProduk) {
                if (this.idPengguna == 0 || prod.getPenjualIdPengguna() == this.idPengguna) {
                    jumlahProduk++;
                }
            }
        }
        jLabel6.setText(String.valueOf(jumlahProduk));

        int pesananMasuk = 0;
        double totalPendapatan = 0.0;
        List<Pesanan> listPesanan = control.ambilSemuaPesanan();
        
        if (listPesanan != null) {
            for (Pesanan pes : listPesanan) {
                if (this.idPengguna == 0 || pes.getPenjualIdPengguna() == this.idPengguna) {
                    // Hitung pesanan aktif/masuk
                    if (pes.getStatusPesanan() == StatusPesanan.Diproses) {
                        pesananMasuk++;
                    }
                    
                    if (pes.getStatusPesanan() == StatusPesanan.Selesai) {
                        totalPendapatan += pes.getTotalBayar();
                    }
                }
            }
        }
        jLabel4.setText(pesananMasuk + " Pesanan");
        
        NumberFormat formatRupiah = NumberFormat.getCurrencyInstance(new Locale("id", "ID"));
        jLabel8.setText(formatRupiah.format(totalPendapatan));
    }


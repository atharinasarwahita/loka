    private void jBtnSimpanProdukActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBtnSimpanProdukActionPerformed
        try {
        
        String nama = jTxtNamaProduk.getText().trim();
        String hargaStr = jTxtHarga.getText().trim();
        String stokStr = jTxtStok.getText().trim();
        String kategori = jCmbKategori.getSelectedItem().toString();
        String beratStr = jTxtBerat.getText().trim();
        String deskripsi = jTxtDeskripsi.getText().trim();
        String gambar = (pathGambar != null && !pathGambar.isEmpty()) ? pathGambar : "default.png";

        if (nama.isEmpty() || hargaStr.isEmpty() || stokStr.isEmpty() || beratStr.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Semua field wajib diisi!", "Peringatan", JOptionPane.WARNING_MESSAGE);
            return;
        }

        double harga = Double.parseDouble(hargaStr);
        int stok = Integer.parseInt(stokStr);
        int berat = Integer.parseInt(beratStr);

        enums.StatusProduk status;
        if (stok <= 0) {
            status = enums.StatusProduk.Habis;
        } else if (stok <= 5) {
            status = enums.StatusProduk.Kritis;
        } else if (stok <= 15) {
            status = enums.StatusProduk.Waspada;
        } else {
            status = enums.StatusProduk.Aman;
        }

        control.tambahProduk(
            0,  
            this.idPenjual,
            nama, 
            deskripsi,
            kategori,        
            gambar,        
            harga,  
            berat,     
            stok,
            status,
            enums.IzinJual.Menunggu, 
            0,            
            new java.util.Date()      
        );

        JOptionPane.showMessageDialog(this, "Produk berhasil ditambahkan!", "Sukses", JOptionPane.INFORMATION_MESSAGE);
        this.dispose();

    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "Harga, Stok, dan Berat harus berupa angka valid!", "Error", JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_jBtnSimpanProdukActionPerformed


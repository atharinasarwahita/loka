    public void setData(int idPembeli, String namaPembeli, String pesanTerakhir, String statusDibaca, ChatPelanggan parent) {
        this.idPembeli = idPembeli;

        jLblNamaPembeli.setText(namaPembeli != null ? namaPembeli : "Pelanggan");

        String preview = pesanTerakhir == null ? "" : pesanTerakhir.replace("\n", " ");
        if (preview.length() > 45) preview = preview.substring(0, 45) + "...";
        jLblPesanTerakhir.setText(preview);

        if ("Belum Dibaca".equalsIgnoreCase(statusDibaca) || "Belum Dibalas".equalsIgnoreCase(statusDibaca)) {
            jLblStatus.setText("Belum Dibalas");
            jLblStatus.setForeground(new java.awt.Color(228, 92, 16));
        } else {
            jLblStatus.setText("Sudah Dibalas");
            jLblStatus.setForeground(new java.awt.Color(75, 93, 22));
        }

        // Event klik untuk membuka room chat
        java.awt.event.MouseAdapter klik = new java.awt.event.MouseAdapter() {
            @Override
            public void mouseClicked(java.awt.event.MouseEvent e) {
                parent.bukaRoomChat(idPembeli, namaPembeli);
            }
        };

        java.awt.Cursor tangan = java.awt.Cursor.getPredefinedCursor(java.awt.Cursor.HAND_CURSOR);
        setCursor(tangan);
        addMouseListener(klik);
        pasangKlikAnak(this, klik, tangan);
    }

    private void pasangKlikAnak(java.awt.Container induk, java.awt.event.MouseAdapter klik, java.awt.Cursor c) {
        for (java.awt.Component anak : induk.getComponents()) {
            anak.setCursor(c);
            anak.addMouseListener(klik);
            if (anak instanceof java.awt.Container) {
                pasangKlikAnak((java.awt.Container) anak, klik, c);
            }
        }
    }

    public int getIdPembeli() {
        return idPembeli;
    }

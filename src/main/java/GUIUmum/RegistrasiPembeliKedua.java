    private void jBtnDaftarSekarangActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBtnDaftarSekarangActionPerformed
        String alamat = jTxtAlamat.getText().trim();
        String kota = jTxtKota.getText().trim();
        String kecamatan = jTxtKecamatan.getText().trim();
        String kodePos = jTxtKodePos.getText().trim();
        String pin = jTxtPin.getText().trim();

        if (alamat.isEmpty() || kota.isEmpty() || kecamatan.isEmpty() || kodePos.isEmpty() || pin.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Semua field alamat dan PIN harus diisi!", "Peringatan", JOptionPane.WARNING_MESSAGE);
            return;
        }

        boolean sukses = control.registerPembeli(namaLengkap, email, jenisKelamin, noHp, password, alamat, kota, kecamatan, kodePos, pin);

        if (sukses) {
            JOptionPane.showMessageDialog(this, "Registrasi Berhasil! Silakan masuk.", "Sukses", JOptionPane.INFORMATION_MESSAGE);
            new GUIUmum.LoginUser().setVisible(true);
            this.dispose();
        } else {
            JOptionPane.showMessageDialog(this, "Registrasi Gagal. Silakan coba lagi.", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jBtnDaftarSekarangActionPerformed


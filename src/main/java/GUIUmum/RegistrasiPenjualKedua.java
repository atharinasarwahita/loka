    private void jBtnDaftarSekarangActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBtnDaftarSekarangActionPerformed
        String alamat = jTextFNamaLengkap.getText().trim();
        String kota = jTextFNamaToko.getText().trim();
        String kec = jTextKategori.getText().trim();
        String pos = jTextNoHP.getText().trim();
        String noIzin = jTextDeskripsi.getText().trim();
        String password = jTextDeskripsi1.getText().trim();

        if (alamat.isEmpty() || kota.isEmpty() || kec.isEmpty() || pos.isEmpty() || password.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Mohon lengkapi alamat dan password toko!", "Peringatan", JOptionPane.WARNING_MESSAGE);
            return;
        }

        try {
            // Panggil Controller LOKA
            controll.LokaControl control = new controll.LokaControl();

            control.registerPenjual(
                0,
                this.namaPemilik,
                this.email,
                password,
                this.noHp,
                this.namaToko,
                this.deskripsi,
                alamat,
                kota,
                kec,
                pos,
                0.0,
                noIzin,
                StatusVerifikasi.BelumDiverifikasi,
                new java.util.Date(),
                StatusAkun.Aktif,     
                new java.util.Date()
            );

            JOptionPane.showMessageDialog(this, "Pendaftaran Merchant Berhasil! Silakan Login.", "Sukses", JOptionPane.INFORMATION_MESSAGE);

            new GUIUmum.LoginUser().setVisible(true);
            this.dispose();

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Gagal mendaftar merchant: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
            e.printStackTrace();
        }
    }//GEN-LAST:event_jBtnDaftarSekarangActionPerformed


    private void muatDataPengajuan() {
        Pesanan p = control.cariPesanan(noPesanan);
        if (p != null) {
            jLblNoPesanan.setText("No. Pesanan: " + p.getNoPesanan());
            jLblTotalHarga.setText("Rp " + String.format("%,.0f", p.getTotalBayar()).replace(',', '.'));
            try {
                List<model.DetailPesanan> listDetail = control.ambilSemuaDetailPesanan();
                if (listDetail != null) {
                    for (model.DetailPesanan dp : listDetail) {
                        if (dp.getPesananNoPesanan() == this.noPesanan) {
                            model.Produk produk = control.cariProduk(dp.getProdukIdProduk());
                            if (produk != null && produk.getGambarProduk() != null) {
                                java.net.URL imageUrl = getClass().getResource("/gambarproduk/" + produk.getGambarProduk());
                                if (imageUrl != null) {
                                    javax.swing.ImageIcon iconOriginal = new javax.swing.ImageIcon(imageUrl);
                                    java.awt.Image imgSkala = iconOriginal.getImage().getScaledInstance(100, 100, java.awt.Image.SCALE_SMOOTH);
                                    jLblGambarProdukRefund.setIcon(new javax.swing.ImageIcon(imgSkala)); // Ganti jLblGambarProdukRefund dengan nama JLabel foto di form pengembalianmu
                                    jLblGambarProdukRefund.setText("");
                                }
                            }
                            break;
                        }
                    }
                }
            } catch (Exception e) {
                // Ignore error image
            }
        }
    }


    private void jBtnKirimPengajuanPengembalianActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBtnKirimPengajuanPengembalianActionPerformed
        String alasan = jTxtAlasan.getText().trim();
        if (alasan.isEmpty() || alasan.equals("Tuliskan Alasan Pengembalian...")) {
            javax.swing.JOptionPane.showMessageDialog(this, "Alasan pengembalian harus diisi!", "Peringatan", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }

        model.Pesanan p = control.cariPesanan(noPesanan);
        if (p != null) {
            int idPengembalianBaru = control.ambilSemuaPengembalian().size() + 1;
            
            // Simpan data pengembalian ke database
            control.ajukanPengembalian(idPengembalianBaru, alasan, p.getTotalBayar(), enums.StatusPengembalian.Diproses, new java.util.Date());
            
            // Update status pesanan jadi pengembalian
            control.updateStatusPesanan(noPesanan, enums.StatusPesanan.Pengembalian, null, null);

            javax.swing.JOptionPane.showMessageDialog(this, "Pengajuan pengembalian berhasil dikirim!", "Sukses", javax.swing.JOptionPane.INFORMATION_MESSAGE);
            new GUIPembeli.Pesanan(idPembeli).setVisible(true);
            this.dispose();
        }
    }//GEN-LAST:event_jBtnKirimPengajuanPengembalianActionPerformed


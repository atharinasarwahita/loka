    private void jBtnHapusActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBtnHapusActionPerformed
        int konfirmasi = javax.swing.JOptionPane.showConfirmDialog(
        this, 
        "Yakin mau hapus produk ini dari keranjang?", 
        "Konfirmasi Hapus", 
        javax.swing.JOptionPane.YES_NO_OPTION,
        javax.swing.JOptionPane.WARNING_MESSAGE
    );
    
    if (konfirmasi == javax.swing.JOptionPane.YES_OPTION) {
        // Cari ID pembeli yang aktif dari form utama KeranjangPembeli di atasnya
        java.awt.Container topParent = this.getParent();
        while (topParent != null && !(topParent instanceof KeranjangPembeli)) {
            topParent = topParent.getParent();
        }
        
        if (topParent instanceof KeranjangPembeli) {
            KeranjangPembeli frameUtama = (KeranjangPembeli) topParent;
            
            // Hapus dari database via LokaControl
            controll.LokaControl control = new controll.LokaControl();
            control.hapusKeranjang(this.idProduk, frameUtama.getIdPembeli()); // Pastikan ada getter getIdPembeli() atau akses langsung variabelnya
            
            // Hapus panel item dari tampilan UI
            java.awt.Container parent = this.getParent();
            if (parent != null) {
                parent.remove(this);
                parent.revalidate();
                parent.repaint();
            }
            
            // Hitung ulang total tagihan di bawah
            frameUtama.hitungTotalTagihan();
        }
    }
    }//GEN-LAST:event_jBtnHapusActionPerformed

